import { useState } from 'react'
import { Gauge, Layers, ShieldCheck, Timer } from 'lucide-react'
import { Badge, Banner, Card, CHART, ChartCard, Confusion, GroupedBars, H2, Segmented, SeriesChart, Stat } from '../ui'
import { REPORTED } from '../reported'
import { f3, pct } from '../lib'

const NAMES: any = { rf_only: 'Random Forest only', rf_diff: 'RF + temporal differences', hybrid: 'Hybrid: RF + differences + SSSM regime posteriors' }
const SHORT: any = { rf_only: 'RF only', rf_diff: 'RF + diff', hybrid: 'Hybrid' }
const curve = (c: any, x: string, y: string) => c[x].map((v: number, i: number) => ({ x: v, y: c[y][i] }))
const isBenign = (k: string) => ['benign', 'normal'].includes(k.toLowerCase())

export default function Results({ app }: any) {
  const [ds, setDs] = useState('cicids2017')
  const d = (app.demo?.datasets ?? []).find((e: any) => e.id === ds)
  const m = d?.metrics
  const v = m?.variants
  const delta = v ? v.hybrid.f1 - v.rf_only.f1 : 0
  const best = v ? Object.keys(NAMES).reduce((a, b) => (v[b].f1 > v[a].f1 ? b : a)) : ''
  const fam = m ? Object.entries(m.per_family_flagged_rate).sort((a: any, b: any) => b[1].n - a[1].n) : []

  return (
    <div className="space-y-12">
      <section>
        <H2 eyebrow="Section A" sub="Quoted from the research repository.">Original repository-reported results</H2>
        <Banner tone="warn">Not reproduced, not live performance, and not comparable with section B.</Banner>
        <Card className="mt-4 overflow-x-auto">
          <table className="tbl">
            <thead><tr>{REPORTED.head.map((h) => <th key={h}>{h}</th>)}</tr></thead>
            <tbody>{REPORTED.rows.map((r) => <tr key={r[0]}>{r.map((c, i) => <td key={i} className={i === 0 ? 'font-semibold' : ''}>{c}</td>)}</tr>)}</tbody>
          </table>
        </Card>
        <ul className="mt-3 list-disc space-y-1 pl-5 text-xs leading-relaxed text-ink2">{REPORTED.caveats.map((c) => <li key={c}>{c}</li>)}</ul>
      </section>

      <section className="space-y-6">
        <H2 eyebrow="Section B" sub="Generated by training and evaluating the pipeline on a chronological split, with predictions from the exported models.">Newly reproduced held-out evaluation</H2>
        <Segmented options={[['cicids2017', 'CICIDS2017'], ['unswnb15', 'UNSW-NB15']]} value={ds} onChange={setDs} />

        {!m ? <p className="text-sm text-ink2">Loading…</p> : (
          <>
            <div className="grid grid-cols-2 gap-4 lg:grid-cols-4">
              <Stat label="Training rows" value={m.rows.train.toLocaleString()} sub={`attack rate ${pct(m.attack_rate.train)}`} tone="blue" icon={Layers} />
              <Stat label="Validation rows" value={m.rows.val.toLocaleString()} sub={`attack rate ${pct(m.attack_rate.val)}`} tone="teal" icon={ShieldCheck} />
              <Stat label="Test rows" value={m.rows.test.toLocaleString()} sub={`attack rate ${pct(m.attack_rate.test)}`} tone="violet" icon={Timer} />
              <Stat label="Decision threshold" value={f3(d.threshold)} sub="selected on validation (max F1)" tone="pink" icon={Gauge} />
            </div>
            <p className="text-xs leading-relaxed text-ink2">One seed, one split: differences of a few hundredths are within noise.</p>

            <div className="grid gap-4 xl:grid-cols-5">
              <ChartCard title="Ablation: what does each component add?" sub="Precision, recall and F1 on the held-out test partition." className="xl:col-span-2">
                <GroupedBars data={Object.keys(NAMES).map((k) => ({ name: SHORT[k], precision: v[k].precision, recall: v[k].recall, f1: v[k].f1 }))}
                  bars={[{ key: 'precision', name: 'Precision', color: CHART.ocean }, { key: 'recall', name: 'Recall', color: CHART.lagoon }, { key: 'f1', name: 'F1', color: CHART.orchid }]} />
              </ChartCard>
              <Card className="overflow-x-auto xl:col-span-3">
                <div className="mb-3 text-sm font-bold text-ink">Ablation table</div>
                <table className="tbl">
                  <thead><tr><th>Variant</th><th>Precision</th><th>Recall</th><th>F1</th><th>FPR</th><th>ROC-AUC</th><th>PR-AUC</th></tr></thead>
                  <tbody>{Object.keys(NAMES).map((k) => (
                    <tr key={k}>
                      <td className="min-w-[14rem] font-semibold">{NAMES[k]} {k === best && <Badge tone="teal" className="ml-1">highest F1</Badge>}</td>
                      {['precision', 'recall', 'f1', 'fpr', 'roc_auc', 'pr_auc'].map((f) => <td key={f}>{f3(v[k][f])}</td>)}
                    </tr>))}
                  </tbody>
                </table>
                <p className="mt-3 text-sm leading-relaxed text-ink">
                  {delta > 0.01 ? `The full hybrid scores ${f3(delta)} F1 above Random Forest alone.` :
                    delta < -0.01 ? `Random Forest alone scores ${f3(-delta)} F1 above the full hybrid: the SSSM regime features did not improve detection on this split.` :
                      'The hybrid and Random Forest alone are within 0.01 F1: no SSSM advantage is demonstrated on this split.'}
                  {' '}The regime posterior alone reaches ROC-AUC {f3(m.sssm_alone_roc_auc)}, so it carries signal, but it is largely redundant with the flow features.
                </p>
              </Card>
            </div>

            <div className="grid gap-4 lg:grid-cols-2">
              <ChartCard title={`ROC curve (hybrid) — AUC ${f3(v.hybrid.roc_auc)}`} sub="From held-out test prediction scores.">
                <SeriesChart data={curve(v.hybrid.roc_curve, 'fpr', 'tpr')} xKey="x" numericX diagonal yDomain={[0, 1]} xLabel="false positive rate" series={[{ key: 'y', name: 'TPR', color: CHART.oceanDeep }]} />
              </ChartCard>
              <ChartCard title={`Precision–recall curve (hybrid) — AP ${f3(v.hybrid.pr_auc)}`} sub="From held-out test prediction scores.">
                <SeriesChart data={curve(v.hybrid.pr_curve, 'recall', 'precision')} xKey="x" numericX yDomain={[0, 1]} xLabel="recall" series={[{ key: 'y', name: 'precision', color: CHART.lagoon }]} />
              </ChartCard>
            </div>

            <div className="grid gap-4 xl:grid-cols-5">
              <ChartCard title="Confusion matrix" sub={`Hybrid, test partition, threshold ${f3(d.threshold)}.`} className="xl:col-span-2">
                <Confusion c={v.hybrid.confusion} />
              </ChartCard>
              <Card className="overflow-x-auto xl:col-span-3">
                <div className="text-sm font-bold text-ink">Share of test rows flagged, by original label (hybrid)</div>
                <p className="mb-3 mt-0.5 text-xs leading-relaxed text-ink2">For benign rows this is the false-alarm rate; for attack classes it is recall. Classes missing from the table had no rows left in the test partition.</p>
                <table className="tbl">
                  <thead><tr><th>Label</th><th>Test rows</th><th>Meaning</th><th>Flagged as attack</th></tr></thead>
                  <tbody>{fam.map(([k, x]: any) => (
                    <tr key={k}>
                      <td className="font-semibold">{k}</td><td>{x.n.toLocaleString()}</td>
                      <td>{isBenign(k) ? <Badge tone="amber">false-alarm rate</Badge> : <Badge tone="teal">recall</Badge>}</td>
                      <td><div className="flex items-center gap-3">
                        <div className="h-2 w-32 rounded-full bg-ocean-tint"><div className={`h-2 rounded-full ${isBenign(k) ? 'bg-sun-line' : 'bg-lagoon-line'}`} style={{ width: `${x.flagged_rate * 100}%` }} /></div>
                        <span>{pct(x.flagged_rate)}</span></div></td>
                    </tr>))}
                  </tbody>
                </table>
              </Card>
            </div>

            <ul className="list-disc space-y-1 pl-5 text-xs leading-relaxed text-ink2">
              {m.notes.map((n: string) => <li key={n}>{n}</li>)}
              <li>Detection lead time is not reported: no validated temporal early-detection experiment supports it. Where used elsewhere, lead time is measured in sequence steps, not seconds.</li>
            </ul>
          </>
        )}
      </section>
    </div>
  )
}